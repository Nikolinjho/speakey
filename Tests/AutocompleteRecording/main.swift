import Foundation

var checks = 0, failures = 0
func check(_ value: Bool, _ name: String) {
    checks += 1
    if !value { failures += 1 }
    print("\(value ? "PASS" : "FAIL"): \(name)")
}
var session = AutocompleteRecordingSession<Int>()
check(session.note(field: 1, bundleID: "editor", text: "Первое поле") == nil, "Первый снимок не завершает сессию")
session.confirmInsertion(field: 1, text: "Известное поле")
check(session.note(field: 1, bundleID: "editor", text: "Первое поле с продолжением") == nil, "Набор в том же поле сохраняет сессию")
let first = session.note(field: 2, bundleID: "editor", text: "Второе поле без принятия")
check(first?.text == "Первое поле с продолжением" && first?.accepted == true, "Смена поля сохраняет первый принятый текст")
let second = session.finish()
check(second?.text == "Второе поле без принятия" && second?.accepted == false, "Принятие первого поля не переходит во второе")
check(session.finish() == nil, "Повторное завершение не создаёт дубль")

_ = session.note(field: 1, bundleID: "editor", text: "Текст редактора")
let app = session.note(field: 1, bundleID: "mail", text: "Текст письма")
check(app?.bundleID == "editor" && app?.text == "Текст редактора", "Смена приложения завершает сессию")
check(session.finish()?.bundleID == "mail", "Новое приложение записано отдельно")

_ = session.note(field: 1, bundleID: "editor", text: "Известное поле")
session.confirmInsertion(field: 1, text: "Известное поле")
let lost = session.note(field: nil, bundleID: "editor", text: "Неопознанное поле")
check(lost?.text == "Известное поле" && lost?.accepted == true, "Потеря идентичности завершает известное поле")
session.confirmInsertion(field: 1, text: "Известное поле")
check(session.finish() == nil, "Неопознанное поле не записывается")
_ = session.note(field: 2, bundleID: "editor", text: "Новое известное поле")
check(session.finish()?.accepted == false, "Принятие неизвестного поля не переносится")

_ = session.note(field: 1, bundleID: "editor", text: "")
session.confirmInsertion(field: 1, text: nil)
check(session.finish() == nil, "Пустая сессия не записывается")
_ = session.note(field: 1, bundleID: "editor", text: "Удалённая сессия")
session.confirmInsertion(field: 1, text: "Известное поле")
session = AutocompleteRecordingSession()
check(session.finish() == nil, "Сброс политики уничтожает ожидающую сессию")
_ = session.note(field: 1, bundleID: "editor", text: "Првиет, мир справа")
session.confirmInsertion(field: 1, text: "Привет, мир справа")
let correction = session.finish()
check(correction?.text == "Привет, мир справа", "Принятое исправление сохраняет фактический текст, включая правую часть")
_ = session.note(field: 1, bundleID: "editor", text: "Текст до отказа")
session.confirmInsertion(field: 1, text: nil)
check(session.finish()?.accepted == false, "Отказ или непроверенная вставка не отмечается принятием")
_ = session.note(field: 2, bundleID: "editor", text: "Другое поле")
session.confirmInsertion(field: 1, text: "Чужой результат")
let mismatch = session.finish()
check(mismatch?.text == "Другое поле" && mismatch?.accepted == false, "Запоздавший результат не пересекает границу поля")
_ = session.note(field: 1, bundleID: "editor", text: "Начало")
session.confirmInsertion(field: 1, text: "Начало продолжения")
check(session.finish(finalText: "Окончательная редакция справа")?.text == "Окончательная редакция справа", "Завершение использует последнюю редакцию исходного поля")
_ = session.note(field: 1, bundleID: "editor", text: "Удалённый текст")
check(session.finish(finalText: "") == nil, "Очищенное перед завершением поле не записывается")
_ = session.note(field: 1, bundleID: "editor", text: nil)
check(session.finish() == nil, "Неполный или недоступный снимок не записывается")
var intents = AutocompleteAcceptanceQueue()
intents.append(.nextWord)
intents.append(.nextWord)
check(intents.take() == .nextWord && intents.take() == .nextWord && intents.take() == nil, "Два быстрых Tab сохраняют два последовательных намерения")
intents.append(.nextWord)
intents.append(.all)
intents.append(.nextWord)
check(intents.take() == .nextWord && intents.take() == .all && intents.take() == nil, "Принять всё завершает очередь после уже ожидающих слов")
intents.append(.nextWord)
intents.clear()
check(intents.take() == nil, "Смена контекста уничтожает отложенное принятие")
for _ in 0..<100 { intents.append(.nextWord) }
var queued = 0
while intents.take() != nil { queued += 1 }
check(queued == 8, "Очередь быстрых нажатий ограничена восемью словами")
print("autocomplete recording: \(checks) checks, \(failures) failures")
exit(failures == 0 ? 0 : 1)
